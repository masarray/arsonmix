#!/usr/bin/env python3
"""Stage EXACT approved Pages console for JUCE WebView2, without a second renderer.

The user's approved /preview/ route displays the /preview-buttons/ variant:
current site/preview-v2 DOM/logic with ONLY approved PNG-button CSS/JS overrides.
The native-only script is appended after the original UI, not a replacement UI.
All paths, bytes, C++ resource lookups and hashes come from this single build step.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import mimetypes
from pathlib import Path
import re
import shutil

ROOT = Path(__file__).resolve().parents[1]
CANONICAL = ROOT / "site" / "preview-v2"
APPROVED_BUTTONS = ROOT / "site" / "preview-buttons" / "assets"
NATIVE_ADAPTER = ROOT / "web" / "approved-native-bridge.js"
OVERRIDES = ("mixer-control-keys.css", "mixer-control-keys.js")
ADAPTER_MARKER = '<script defer src="assets/approved-native-bridge.js"></script>'
SCHEMA = "arsonmix.approved-native-pages-bundle.v1"


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def accepted_pages_html() -> str:
    """Recreate exactly the generated /preview-buttons/index.html Pages body."""
    html = (CANONICAL / "index.html").read_text(encoding="utf-8")
    for name in OVERRIDES:
        source = APPROVED_BUTTONS / name
        if not source.is_file():
            raise ValueError(f"Missing user-approved Pages button skin: {source}")
        token = "assets/" + name
        pattern = re.compile(re.escape(token) + r'(?:\?[^"\s>]+)?')
        matches = list(pattern.finditer(html))
        if len(matches) != 1:
            raise ValueError(f"Expected exactly one Pages reference to {token}: {len(matches)}")
        m = matches[0]
        rev = sha256(source.read_bytes())[:16]
        html = html[:m.start()] + token + "?rev=" + rev + html[m.end():]
    return html


def native_html() -> str:
    html = accepted_pages_html()
    if html.count("</body>") != 1 or ADAPTER_MARKER in html:
        raise ValueError("Approved GUI must have exactly one body and no prior native injection")
    # One invisible native transport seam. The approved DOM/CSS/controls are unchanged.
    return html.replace("</body>", ADAPTER_MARKER + "\n</body>")


def safe_symbol(filename: str) -> str:
    # JUCE 8 BinaryData: 'mixer-control-keys.css' -> 'mixercontrolkeys_css'
    stem, ext = filename.rsplit(".", 1)
    return re.sub(r"[^A-Za-z0-9_]", "", stem).replace("_", "") + "_" + re.sub(r"[^A-Za-z0-9]", "", ext)


def create_resource_header(files: list[Path]) -> str:
    symbols = {}
    output = [
        "// Generated by scripts/build_approved_native_gui.py. DO NOT EDIT.",
        "// One approved Pages renderer: no legacy web/index.html or console-native.html.",
        "#pragma once",
        "inline bool resolveApprovedGuiResource(const juce::String& request,",
        "                                       const char*& data, int& size, juce::String& mime)",
        "{",
        '    const auto path = request.upToFirstOccurrenceOf("?", false, false);',
    ]
    for file in files:
        path = file.relative_to(file.parent.parent) if file.parent.name == "assets" else Path("index.html")
        url = "/" + path.as_posix()
        sym = safe_symbol(file.name)
        if sym in symbols:
            raise ValueError(f"JUCE BinaryData symbol collision: {sym}: {symbols[sym]}, {url}")
        symbols[sym] = url
        mime = mimetypes.guess_type(file.name)[0] or "application/octet-stream"
        if file.suffix.lower() == ".js":
            mime = "text/javascript"
        if file.suffix.lower() == ".css":
            mime = "text/css"
        condition = '(path == "/" || path == "/index.html")' if url == "/index.html" else f"(path == {json.dumps(url)})"
        output.extend([
            f"    if {condition}",
            "    {",
            f"        data = BinaryData::{sym};",
            f"        size = BinaryData::{sym}Size;",
            f"        mime = {json.dumps(mime)};",
            "        return true;",
            "    }",
        ])
    output.extend(["    return false;", "}", ""])
    return "\n".join(output)


def stage(out: Path) -> dict:
    out = out.resolve()
    if out in (ROOT, ROOT / "site", ROOT / "web", CANONICAL) or (out / ".git").exists():
        raise ValueError(f"Unsafe bundle destination: {out}")
    if out.exists():
        shutil.rmtree(out)
    assets = out / "assets"
    shutil.copytree(CANONICAL / "assets", assets)
    # Exact /preview/ skin, not /preview-v2/ default button controls.
    for name in OVERRIDES:
        shutil.copyfile(APPROVED_BUTTONS / name, assets / name)
    shutil.copyfile(APPROVED_BUTTONS / "mute-solo-pfl-56x37.png", assets / "mute-solo-pfl-56x37.png")
    shutil.copyfile(NATIVE_ADAPTER, assets / "approved-native-bridge.js")
    approved = accepted_pages_html().encode("utf-8")
    html = native_html().encode("utf-8")
    (out / "index.html").write_bytes(html)
    files = [out / "index.html", *sorted(p for p in assets.rglob("*") if p.is_file())]
    if any(p.is_symlink() or p.relative_to(out).parts[0] not in ("index.html", "assets") for p in files):
        raise ValueError("Unsafe native resource input")
    names = [p.relative_to(out).as_posix() for p in files]
    if len(names) != len(set(names)):
        raise ValueError("Duplicate GUI asset resource")
    (out / "ApprovedGuiResources.h").write_text(create_resource_header(files), encoding="utf-8")
    manifest = {
        "schema": SCHEMA,
        "authoritativePagesRoute": "/preview/",
        "authoritativePagesIframe": "/preview-buttons/index.html",
        "canonicalSource": "site/preview-v2/index.html",
        "canonicalSourceSha256": sha256((CANONICAL / "index.html").read_bytes()),
        "approvedPagesHtmlSha256": sha256(approved),
        "nativeHtmlSha256": sha256(html),
        "adapter": "web/approved-native-bridge.js",
        "adapterState": "SCAFFOLD_ONLY__NOT_LIVE_PCM",
        "files": [{"path":p.relative_to(out).as_posix(), "sha256":sha256(p.read_bytes())} for p in files],
    }
    (out / "approved-gui-manifest.json").write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    return manifest


def verify(out: Path) -> dict:
    if not out.is_dir():
        raise ValueError("Native GUI bundle was never generated")
    manifest_file = out / "approved-gui-manifest.json"
    before = manifest_file.read_bytes()
    existing = json.loads(before)
    # Reproduce in a separate temporary location, avoiding mutation during audit.
    import tempfile
    with tempfile.TemporaryDirectory(prefix="armix-approved-gui-check-") as tmp:
        copy = Path(tmp) / "staged"
        expected = stage(copy)
        if existing != expected:
            raise ValueError("STALE OR WRONG APPROVED GUI BUNDLE: manifest changed")
        for relative in ("index.html", "ApprovedGuiResources.h", "approved-gui-manifest.json",
                         *(p["path"] for p in expected["files"])):
            if (out / relative).read_bytes() != (copy / relative).read_bytes():
                raise ValueError(f"STALE OR WRONG APPROVED GUI BUNDLE: {relative}")
    return existing


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", required=True, type=Path)
    parser.add_argument("--verify", action="store_true")
    args = parser.parse_args()
    result = verify(args.out) if args.verify else stage(args.out)
    print("APPROVED_NATIVE_GUI_BUNDLE_OK", result["approvedPagesHtmlSha256"],
          len(result["files"]), "assets", result["adapterState"])


if __name__ == "__main__":
    main()
