sync.edit("timeMs",800);sync.begin("echo");sync.edit("echo",.6);
assert(!sync.snapshot(base));assert.equal(sync.desired.timeMs,800);
assert(!sync.ack({...sent[0],lease:{...lease,epoch:"9"},applied:true,accepted:sent[0].settings},20));
assert(sync.ack({...sent[0],applied:true,accepted:sent[0].settings},35));
assert.equal(sync.desired.timeMs,800);assert.equal(sync.desired.echo,.6);assert.equal(sent.length,2);
sync.edit("timeMs",900);sync.end("timeMs",36);sync.end("echo",37);
assert(sync.ack({...sent[1],applied:true,accepted:sent[1].settings},70));
assert.equal(sent.length,3);assert.equal(sent[2].settings.timeMs,900);
assert(!sync.ack({...sent[0],applied:true,accepted:sent[0].settings},71));
assert(sync.ack({...sent[2],applied:true,accepted:sent[2].settings},80));
assert(sync.stable());assert.equal(sync.accepted.timeMs,900);assert(!sync.snapshot(base));
sync.edit("feedback",.4);assert(sync.tick(120));
sync.edit("feedback",.5);assert(!sync.tick(4000));assert.equal(sync.blocked,"ACK_TIMEOUT");
assert(!sync.recover({...base,revision:3,accepted:sync.accepted},false));
assert(sync.ack({...sent[3],applied:true,accepted:sent[3].settings},4001));
assert.equal(sent[4].settings.feedback,.5);
assert(sync.ack({...sent[4],applied:true,accepted:sent[4].settings},4002));
assert(sync.stable());
